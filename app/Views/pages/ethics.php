            <h2>1. Trazabilidad del material</h2>
            <p>Todo caso debe declarar la especie, la procedencia del material y, cuando aplique, el estado sanitario. No se aceptan publicaciones que presenten como propio material colectado sin permisos o que omitan una fuente evidente. Si el material proviene de una colección, banco o vivero, se indica.</p>

            <h2>2. Reproducibilidad</h2>
            <p>El protocolo debe incluir condiciones suficientes para intentar una réplica: explante, desinfección, medio, reguladores, temperatura, luz y duración. No se exige que el resultado se repita en otro laboratorio, pero sí que el método se describa con precisión. Un protocolo sin concentraciones o sin tiempos no cumple el criterio.</p>

            <h2>3. Resultados honestos</h2>
            <p>Se publican resultados negativos, contaminaciones, pérdidas y ajustes. No se aceptan cifras inventadas ni rangos presentados como mediciones. Los datos demostrativos deben estar marcados como tales. Si una conclusión no se sostiene con el diseño, se pide cambiarla o rechazarla.</p>

            <h2>4. Consentimiento y datos personales</h2>
            <p>No se publican nombres de personas, teléfonos, correos, direcciones, matrículas ni documentos de identidad sin consentimiento. Las imágenes de personas requieren autorización. Las constancias de verificación se guardan en un directorio privado y sólo las consulta el equipo editorial.</p>

            <h2>5. Material sensible y normativa</h2>
            <p>El portal no sustituye permisos de colecta, autorizaciones sanitarias, protocolos de bioseguridad ni evaluaciones de riesgo. Si el trabajo involucra organismos genéticamente modificados, material regulado o especies protegidas, el autor debe declarar el marco aplicable y no publicar información que comprometa poblaciones silvestres.</p>

            <h2>6. Conflicto de interés</h2>
            <p>Si el autor trabaja para una empresa, recibe financiamiento o tiene una relación comercial con el material o el proveedor mencionado, debe declararlo en el texto. La declaración no impide publicar; la omisión sí es motivo de revisión.</p>

            <h2>7. Crédito y licencia</h2>
            <p>Cada publicación declara una licencia. El portal recibe una licencia no exclusiva para publicar y conservar el contenido. El autor conserva la autoría. Si se reutiliza una figura de otro trabajo, se cita y se verifica que la licencia lo permita.</p>

            <h2>8. Moderación</h2>
            <p>Los comentarios deben aportar información, preguntas o críticas argumentadas. Se ocultan insultos, acoso, spam, datos personales y afirmaciones médicas o comerciales sin sustento. La decisión editorial se registra en la auditoría.</p>

            <h2>9. Correcciones</h2>
            <p>Si encuentras un error, escribe a <a href="mailto:hola@vitrolab.mx">hola@vitrolab.mx</a> con el enlace, el dato y la fuente. Las correcciones relevantes se anotan en la publicación. No se reescribe silenciosamente un resultado.</p>
